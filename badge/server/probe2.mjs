import { connect } from "./mcp.mjs";
const c = await connect("probe");
const task = "t-" + Date.now();
await c.call("agntid_task_open", { task_id: task, agent_id: "analyst", user_id: "you", prompt: "Check the status of ticket LAB-TKT-100" });
const r = await c.call("demo_get_ticket", { ticket_id: "LAB-TKT-100", agntid_task_id: task });
const body = JSON.parse(r.result.content[0].text);
const f = body.__agntid_execution_flow;
console.log("isError:", r.result.isError, "| top keys:", Object.keys(body));
for (const s of f.steps) console.log("-", s.step, s.status, JSON.stringify(s.details).slice(0, 300));
console.log("flow keys:", Object.keys(f));
const rest = { ...body }; delete rest.__agntid_execution_flow; console.log("payload:", JSON.stringify(rest).slice(0, 500));
await c.call("agntid_task_close", { task_id: task });
